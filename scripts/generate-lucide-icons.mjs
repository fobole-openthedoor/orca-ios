#!/usr/bin/env node
// Generates App/Design/LucideIcons.generated.swift from the Lucide icons the official app imports.
// Usage: node scripts/generate-lucide-icons.mjs <official mobile dir> <lucide icons dir>
// e.g.   node scripts/generate-lucide-icons.mjs ~/orca/mobile ~/orca/mobile/node_modules/lucide-react-native/dist/esm/icons
// The icon modules are read as text and their element arrays parsed as JSON; nothing is executed.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const [mobileDir, iconsDir] = process.argv.slice(2)
if (!mobileDir || !iconsDir) {
  console.error('usage: generate-lucide-icons.mjs <official mobile dir> <lucide icons dir>')
  process.exit(1)
}
const outFile = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'App/Design/LucideIcons.generated.swift')

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.')) continue
    const full = path.join(dir, name)
    if (statSync(full).isDirectory()) walk(full, out)
    else if (/\.(tsx?|mts)$/.test(name)) out.push(full)
  }
  return out
}

// Every name imported from lucide-react-native in the official app.
const used = new Set()
for (const file of [...walk(path.join(mobileDir, 'src')), ...walk(path.join(mobileDir, 'app'))]) {
  const text = readFileSync(file, 'utf8')
  for (const match of text.matchAll(/import\s*\{([^}]*)\}\s*from\s*'lucide-react-native'/g)) {
    for (const part of match[1].replace(/\/\/[^\n]*/g, '').split(',')) {
      const name = part.replace(/^\s*type\s+/, '').replace(/\s+as\s+.*$/, '').trim()
      if (name && !/^Lucide/.test(name)) used.add(name)
    }
  }
}

// Display name -> element array, from each icon module's createLucideIcon("Name", [...]) call.
const icons = new Map()
for (const name of readdirSync(iconsDir)) {
  if (!name.endsWith('.mjs')) continue
  const text = readFileSync(path.join(iconsDir, name), 'utf8')
  const match = /createLucideIcon\("(\w+)",\s*(\[[\s\S]*?\])\);/.exec(text)
  if (!match || !used.has(match[1])) continue
  const json = match[2].replace(/(\w+):\s/g, '"$1": ')
  icons.set(match[1], JSON.parse(json))
}
// Aliases (Edit3 -> PenLine…) live in separate modules that re-export; fall back to the lucide-icons index.
const missing = [...used].filter((name) => !icons.has(name))
if (missing.length > 0) {
  const indexText = readFileSync(path.join(iconsDir, '..', 'lucide-react-native.mjs'), 'utf8')
  for (const name of missing) {
    const alias = new RegExp(`default as ${name}\\b[^']*'\\./icons/([\\w-]+)\\.mjs'`).exec(indexText)
    if (!alias) continue
    const text = readFileSync(path.join(iconsDir, `${alias[1]}.mjs`), 'utf8')
    const match = /createLucideIcon\("(\w+)",\s*(\[[\s\S]*?\])\);/.exec(text)
    if (match) icons.set(name, JSON.parse(match[2].replace(/(\w+):\s/g, '"$1": ')))
  }
}
const unresolved = [...used].filter((name) => !icons.has(name))
if (unresolved.length > 0) {
  console.error(`unresolved icons: ${unresolved.join(', ')}`)
}

const swiftString = (value) => JSON.stringify(String(value))
const num = (value) => (value === undefined ? '0' : String(Number(value)))

function element([tag, attrs]) {
  switch (tag) {
    case 'path':
      return `.path(${swiftString(attrs.d)})`
    case 'circle':
      return `.circle(cx: ${num(attrs.cx)}, cy: ${num(attrs.cy)}, r: ${num(attrs.r)})`
    case 'ellipse':
      return `.ellipse(cx: ${num(attrs.cx)}, cy: ${num(attrs.cy)}, rx: ${num(attrs.rx)}, ry: ${num(attrs.ry)})`
    case 'rect':
      return `.rect(x: ${num(attrs.x)}, y: ${num(attrs.y)}, width: ${num(attrs.width)}, height: ${num(attrs.height)}, rx: ${num(attrs.rx ?? attrs.ry)}, ry: ${num(attrs.ry ?? attrs.rx)})`
    case 'line':
      return `.line(x1: ${num(attrs.x1)}, y1: ${num(attrs.y1)}, x2: ${num(attrs.x2)}, y2: ${num(attrs.y2)})`
    case 'polyline':
      return `.polyline(${swiftString(attrs.points)})`
    case 'polygon':
      return `.polygon(${swiftString(attrs.points)})`
    default:
      throw new Error(`unknown element ${tag}`)
  }
}

const lowerFirst = (name) => name[0].toLowerCase() + name.slice(1)
const names = [...icons.keys()].sort()
const lines = [
  '// Generated by scripts/generate-lucide-icons.mjs from lucide-react-native (ISC). Do not edit.',
  '',
  'extension Lucide {'
]
for (const name of names) {
  lines.push(`  static let ${lowerFirst(name)} = Lucide(name: ${swiftString(name)}, elements: [`)
  for (const item of icons.get(name)) lines.push(`    ${element(item)},`)
  lines.push('  ])')
}
lines.push('}', '')
writeFileSync(outFile, lines.join('\n'))
console.log(`wrote ${names.length} icons to ${path.relative(process.cwd(), outFile)}`)
